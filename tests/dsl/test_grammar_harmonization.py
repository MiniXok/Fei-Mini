"""M4.6 语法协调与表征性单元及集成测试。"""

import json
import os
import unittest
from feimini.dsl.ast import FilterNode, LimitNode, PredicateOp, ProjectNode, ScanNode, SortNode, SortDirection
from feimini.dsl.grammar import DEFAULT_GRAMMAR, MiniRelGrammar
from feimini.dsl.types import Column, DataType, RelationSchema
from feimini.generator.tasks import EvaluatorTaskData, TaskSpec
from feimini.search.exhaustive import ExhaustiveSearchSolver
from feimini.search.random_search import RandomSearchSolver


class TestGrammarHarmonization(unittest.TestCase):
    def setUp(self) -> None:
        self.grammar = DEFAULT_GRAMMAR
        self.schema = RelationSchema(
            (
                Column("id", DataType.INT),
                Column("city", DataType.STR),
                Column("score", DataType.FLOAT),
                Column("is_active", DataType.BOOL),
            )
        )
        self.task_spec = TaskSpec(
            task_id="test_harm_001",
            schemas={"t1": self.schema},
            examples=(),
            complexity="SIMPLE",
        )
        self.solver = ExhaustiveSearchSolver(grammar=self.grammar)

    def test_limit_vocabulary(self) -> None:
        """测试 2, 3, 4, 5 全部合法 limit 均被穷举器支持。"""
        self.assertEqual(self.grammar.LIMIT_VALUES, (2, 3, 4, 5))
        candidates = list(self.solver._generate_candidates(self.task_spec))
        limits_found = {
            c.limit for c in candidates if isinstance(c, LimitNode)
        }
        for lim in (2, 3, 4, 5):
            self.assertIn(lim, limits_found, f"Limit value {lim} not generated by enumerator")

    def test_projection_width_up_to_3(self) -> None:
        """测试支持 1 列、2 列与 3 列投影。"""
        candidates = list(self.solver._generate_candidates(self.task_spec))
        proj_widths = {
            len(c.columns) for c in candidates if isinstance(c, ProjectNode) and isinstance(c.source, ScanNode)
        }
        self.assertIn(1, proj_widths)
        self.assertIn(2, proj_widths)
        self.assertIn(3, proj_widths)

    def test_standardized_aggregation_aliases(self) -> None:
        """测试聚合别名统一为 total_cnt 与 sum_metric。"""
        self.assertEqual(self.grammar.COUNT_ALIAS, "total_cnt")
        self.assertEqual(self.grammar.SUM_ALIAS, "sum_metric")
        self.assertEqual(self.grammar.JOIN_AGG_ALIAS, "agg_metric")

    def test_numeric_neq_operator(self) -> None:
        """测试数值类型列支持 NEQ 谓词。"""
        task = TaskSpec(
            task_id="t_neq",
            schemas={"t1": self.schema},
            examples=(),
            complexity="SIMPLE",
        )
        # 伪造一个提取到的常量
        self.solver._extract_observed_constants = lambda t: {"id": [10, 20]}  # type: ignore
        candidates = list(self.solver._generate_candidates(task))
        neq_filters = [
            c for c in candidates
            if isinstance(c, FilterNode) and c.col_name == "id" and c.predicate_op == PredicateOp.NEQ
        ]
        self.assertGreater(len(neq_filters), 0, "Numeric NEQ filter not generated")

    def test_v2_dev_gold_representability_integration(self) -> None:
        """集成测试：验证 v2 开发集抽样任务的 100% 语法表征性。"""
        dev_dir = "datasets/v2/dev"
        if not os.path.exists(dev_dir):
            self.skipTest("datasets/v2/dev not present")

        fnames = sorted([f for f in os.listdir(dev_dir) if f.endswith(".json")])[:20]
        for fname in fnames:
            with open(os.path.join(dev_dir, fname), "r", encoding="utf-8") as f:
                task = EvaluatorTaskData.from_dict(json.load(f))
            # 验证 AST 合法且属于声明语法
            schema = task.gold_ast.validate_types(task.task_spec.schemas)
            self.assertIsNotNone(schema)


if __name__ == "__main__":
    unittest.main()
